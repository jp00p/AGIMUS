DROP TABLE IF EXISTS arena_polls;
DROP TABLE IF EXISTS arena_episodes;

CREATE TABLE arena_episodes (
    id int NOT NULL AUTO_INCREMENT PRIMARY KEY,
    show_name varchar(20) NOT NULL,
    number int NOT NULL,
    episode_name varchar(255) NOT NULL,
    rank_points float NOT NULL DEFAULT 0,
    number_of_matches int NOT NULL DEFAULT 0,
    UNIQUE (show_name, number),
    INDEX (rank_points),
    INDEX (number_of_matches)
);

CREATE TABLE arena_polls (
    message_id bigint PRIMARY KEY,  -- Since each message for a poll is already unique, we can use it as the primary key
    episode_a_id int NOT NULL REFERENCES arena_episodes(id),
    episode_b_id int NOT NULL REFERENCES arena_episodes(id),
    created_at datetime DEFAULT CURRENT_TIMESTAMP,
    updated_at datetime ON UPDATE CURRENT_TIMESTAMP,
    result float DEFAULT NULL,
    voter_count int DEFAULT NULL
);

